package com.rootgenie.app.modules

import android.content.Context
import com.rootgenie.app.ModuleSpec
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Turns a ModuleSpec into a real flashable Magisk module zip.
 * Structure follows the official Magisk module format:
 *   module.prop, customize.sh, system.prop (optional), files..., META-INF stub.
 * Install later with: magisk --install-module <zip>
 */
object ModuleFactory {

    fun outputDir(ctx: Context): File =
        File(ctx.cacheDir, "generated_modules").apply { mkdirs() }

    private fun sanitizePath(p: String): String? {
        val clean = p.trim().trimStart('/')
        if (clean.isEmpty()) return null
        if (clean.contains("..")) return null
        val allowed = clean.startsWith("system/") || clean.startsWith("META-INF/") ||
                clean.startsWith("post-fs-data.d/") || clean.startsWith("service.d/")
        return if (allowed || clean == "system.prop" || clean == "customize.sh" || clean == "webroot/") clean else null
    }

    fun build(ctx: Context, spec: ModuleSpec): File {
        val dir = outputDir(ctx)
        val outFile = File(dir, "${spec.id}_${System.currentTimeMillis()}.zip")

        ZipOutputStream(outFile.outputStream().buffered()).use { zip ->
            fun entry(name: String, content: String, exec: Boolean = false) {
                val e = ZipEntry(name)
                e.time = System.currentTimeMillis()
                zip.putNextEntry(e)
                zip.write(content.toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }

            // module.prop — required by Magisk
            entry("module.prop", """
                id=${spec.id}
                name=${spec.name}
                version=${spec.version}
                versionCode=1
                author=${spec.author}
                description=${spec.description.replace('\n', ' ')}
            """.trimIndent() + "\n")

            // customize.sh
            val script = spec.script.ifBlank {
                """
                # Generated by RootGenie
                ui_print "- Installing ${spec.name} ${spec.version}"
                ui_print "- Generated by RootGenie AI"
                if [ -d "${'$'}MODPATH/system" ]; then
                  set_perm_recursive "${'$'}MODPATH/system" 0 0 0755 0644
                fi
                ui_print "- Done! Reboot to apply."
                """.trimIndent() + "\n"
            }
            entry("customize.sh", script, exec = true)

            // system.prop
            if (spec.props.isNotBlank()) {
                entry("system.prop", spec.props.trim() + "\n")
            }

            // extra files
            for (f in spec.files) {
                val safe = sanitizePath(f.path) ?: continue
                entry(safe, f.content)
            }

            // META-INF stub (Magisk app doesn't need it; warns recovery users)
            entry("META-INF/com/google/android/update-binary",
                "#!/sbin/sh\necho 'This module must be installed via the Magisk app.'\nexit 1\n", exec = true)
            entry("META-INF/com/google/android/updater-binary",
                "#!/sbin/sh\necho 'This module must be installed via the Magisk app.'\nexit 1\n", exec = true)
        }
        return outFile
    }
}
